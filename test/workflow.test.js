import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import { start } from '../server.js';
import { Generator } from '../lib/generator.js';
import { atomicJSON, loadProject, projectDir, safeFile, validSource } from '../lib/storage.js';

const fixture = fileURLToPath(new URL('./fake-codex.mjs', import.meta.url));
await fs.chmod(fixture, 0o755);
const wait = ms => new Promise(r => setTimeout(r, ms));
test('complete persistent workflow, revisions, attachments, isolation, resume, failure and restart', async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), '.vizualearner-test-'));
  const makeServer = () => start({ port: 0, artifactPort: 0, stateDir: temp, seed: false, generator: new Generator({ bin: fixture, timeout: 15000 }) });
  let running = await makeServer();
  t.after(async () => { await running.close(); await fs.rm(temp, { recursive: true, force: true }); });
  let config = await fetch(running.url + '/api/config').then(r => r.json());
  const api = async (url, method = 'GET', body) => {
    const headers = { 'X-Lab-Token': config.token }; if (body && !(body instanceof FormData)) { headers['Content-Type'] = 'application/json'; body = JSON.stringify(body); }
    const r = await fetch(running.url + url, { method, headers, body });
    const value = await r.json(); assert.ok(r.ok, JSON.stringify(value)); return value;
  };
  const finished = async pid => {
    for (let i = 0; i < 150; i++) { const p = await api('/api/projects/' + pid); if (p.status !== 'generating') return p; await wait(50); }
    throw new Error('Generation did not finish.');
  };
  const p = await api('/api/projects', 'POST');
  const form = new FormData(); form.append('message', 'Draw an interactive unit circle'); form.append('model', 'test-math-model'); form.append('effort', 'high'); form.append('attachments', new Blob(['A circle of radius one']), 'notes.txt');
  await api(`/api/projects/${p.id}/messages`, 'POST', form);
  let saved = await finished(p.id);
  assert.equal(saved.status, 'ready'); assert.ok(saved.sessionId); assert.equal(saved.messages.length, 2); assert.equal(saved.attachments.length, 1);
  assert.ok(saved.lastRunTiming.durationMs >= 250);
  assert.equal(saved.messages.at(-1).durationMs, saved.lastRunTiming.durationMs);
  assert.ok(Date.parse(saved.lastRunTiming.completedAt) >= Date.parse(saved.lastRunTiming.startedAt));
  assert.equal(saved.generationStartedAt, null);
  const disk = await loadProject(config.workspace, p.id);
  assert.ok(disk.messages.some(m => m.rawResponse?.files.length === 2 && m.rawText));
  const firstRevision = saved.currentRevision;
  const artifact = await fetch(`${config.artifactOrigin}/view/${p.id}/${firstRevision}/index.html`);
  assert.equal(artifact.status, 200); assert.match(artifact.headers.get('content-security-policy'), /sandbox allow-scripts/); assert.match(await artifact.text(), /main.js/);
  assert.equal((await fetch(`${config.artifactOrigin}/view/${p.id}/${firstRevision}/main.js`)).status, 200);
  await api(`/api/projects/${p.id}/revisions/${firstRevision}/render`, 'POST', { frameLoadMs: 42 });
  assert.equal((await api(`/api/projects/${p.id}`)).renderMetrics.frameLoadMs, 42);
  const originalSession = saved.sessionId;
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'Add a slider', model: 'test-refined-model', effort: 'xhigh' });
  saved = await finished(p.id);
  assert.equal(saved.status, 'ready'); assert.equal(saved.messages.length, 4); assert.equal(saved.revisions.length, 2);
  assert.ok(saved.messages.at(-1).durationMs >= 250);
  const runDir = path.join(projectDir(config.workspace, p.id), 'runs', saved.revisions.at(-1).runId);
  const invocation = JSON.parse(await fs.readFile(path.join(runDir, 'invocation.json')));
  assert.equal(invocation[invocation.indexOf('resume') + 1], saved.sessionId);
  assert.equal(saved.sessionId, originalSession);
  assert.ok(invocation.includes('read-only')); assert.ok(invocation.includes('never'));
  assert.equal(invocation[invocation.indexOf('--model') + 1], 'test-refined-model');
  assert.ok(invocation.includes('model_reasoning_effort="xhigh"'));
  assert.deepEqual(saved.generationSettings, { model: 'test-refined-model', effort: 'xhigh' });
  assert.deepEqual(saved.messages.filter(m => m.role === 'user').at(-1).generationSettings, saved.generationSettings);
  const context = JSON.parse(await fs.readFile(path.join(runDir, 'context.json')));
  assert.equal(context.baseRevision, firstRevision);
  assert.equal(context.source.length, 2);
  assert.equal(context.source[0].sha256.length, 64);
  assert.equal(context.messages, undefined);
  await assert.rejects(fs.access(path.join(runDir, 'conversation.json')));
  assert.equal(saved.lastRunTiming.stats.outputMode, 'patch');
  assert.ok(saved.lastRunTiming.phases.codexMs >= 250);
  assert.ok(saved.lastRunTiming.usage.output_tokens > 0);
  assert.match(await fs.readFile(path.join(runDir, 'current-source/index.html'), 'utf8'), /Angle/);
  const second = await api('/api/projects', 'POST');
  assert.equal(second.messages.length, 0); assert.equal(second.sessionId, null);
  assert.equal((await api(`/api/projects/${p.id}`)).currentRevision, saved.currentRevision);
  await api(`/api/projects/${second.id}/messages`, 'POST', { message: 'An independent circle exploration' });
  const separate = await finished(second.id);
  assert.notEqual(separate.sessionId, saved.sessionId);
  assert.equal(separate.messages.filter(m => m.role === 'user').length, 1);
  const goodRevision = saved.currentRevision;
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'BAD_PATCH_TEST' });
  const recoveredPatch = await finished(p.id);
  assert.equal(recoveredPatch.status, 'ready');
  assert.equal(recoveredPatch.sessionId, originalSession);
  assert.equal(recoveredPatch.lastRunTiming.stats.attempts, 2);
  assert.equal(recoveredPatch.lastRunTiming.stats.patchFallback, true);
  assert.equal(recoveredPatch.lastRunTiming.stats.outputMode, 'complete');
  assert.deepEqual(recoveredPatch.generationSettings, saved.generationSettings);
  const latestGoodRevision = recoveredPatch.currentRevision;
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'BAD_JS_TEST' });
  const syntaxFailure = await finished(p.id);
  assert.equal(syntaxFailure.status, 'error');
  assert.equal(syntaxFailure.currentRevision, latestGoodRevision);
  assert.match(syntaxFailure.messages.at(-1).content, /JavaScript syntax error/);
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'FAIL_TEST' });
  saved = await finished(p.id); assert.equal(saved.status, 'error'); assert.equal(saved.currentRevision, latestGoodRevision); assert.match(saved.messages.at(-1).content, /Synthetic/);
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'SLOW_TEST' });
  const simultaneous = await fetch(`${running.url}/api/projects/${p.id}/messages`, { method: 'POST', headers: { 'X-Lab-Token': config.token, 'Content-Type': 'application/json' }, body: '{"message":"second request"}' });
  assert.equal(simultaneous.status, 409);
  await wait(150); await api(`/api/projects/${p.id}/cancel`, 'POST');
  saved = await finished(p.id); assert.equal(saved.status, 'cancelled'); assert.equal(saved.currentRevision, latestGoodRevision);
  assert.ok(saved.messages.at(-1).durationMs >= 0);
  assert.equal(saved.lastRunTiming.status, 'cancelled');
  const denied = await fetch(running.url + '/api/projects', { method: 'POST' }); assert.equal(denied.status, 403);
  const wrongOrigin = await fetch(running.url + '/api/projects', { method: 'POST', headers: { 'X-Lab-Token': config.token, Origin: 'https://evil.example' } }); assert.equal(wrongOrigin.status, 403);
  const reboundStatus = await new Promise((resolve, reject) => { http.get(running.url + '/api/config', { headers: { Host: 'evil.example' } }, res => { res.resume(); resolve(res.statusCode); }).on('error', reject); }); assert.equal(reboundStatus, 403);
  const attachment = await fetch(`${running.url}/api/projects/${p.id}/attachments/${saved.attachments[0].id}`); assert.equal(await attachment.text(), 'A circle of radius one');
  await running.close();
  // Simulate a server that was killed before it could save the interrupted state.
  saved.status = 'generating'; await atomicJSON(path.join(projectDir(config.workspace, p.id), 'project.json'), saved);
  running = await makeServer(); config = await fetch(running.url + '/api/config').then(r => r.json());
  saved = await api(`/api/projects/${p.id}`); assert.equal(saved.status, 'interrupted'); assert.equal(saved.currentRevision, latestGoodRevision); assert.ok(saved.messages.some(m => m.content.includes('FAIL_TEST')));
  saved.sessionId = '00000000-0000-0000-0000-000000000000'; await atomicJSON(path.join(projectDir(config.workspace, p.id), 'project.json'), saved);
  await api(`/api/projects/${p.id}/messages`, 'POST', { message: 'Restore and keep working' });
  saved = await finished(p.id); assert.equal(saved.status, 'ready'); assert.ok(saved.messages.some(m => m.role === 'system' && m.content.includes('unavailable'))); assert.notEqual(saved.sessionId, '00000000-0000-0000-0000-000000000000');
  const restoredPath = path.join(projectDir(config.workspace, p.id), 'runs', saved.revisions.at(-1).runId, 'conversation.json');
  const restored = JSON.parse(await fs.readFile(restoredPath, 'utf8'));
  assert.ok(restored.messages.filter(m => m.role === 'user').length >= 6);
  assert.ok(restored.messages.every(m => m.rawResponse === undefined && m.rawText === undefined));
  const custom = path.join(temp, 'chosen-workspace'); await api('/api/workspace', 'POST', { path: custom }); assert.deepEqual(await api('/api/projects'), []);
  await api('/api/workspace', 'POST', { path: path.join(temp, 'workspace') }); assert.equal((await api('/api/projects')).length, 2);
});

test('source validation and symlink containment reject unsafe generated paths', async () => {
  const source = p => [{ path: 'index.html', content: '<html>test</html>' }, { path: p, content: 'test' }];
  for (const p of ['../escape.js', '/tmp/script.js', 'a/../../escape.js', '.hidden.js', 'test.exe', 'a//b.js', 'index.html']) assert.throws(() => validSource(source(p)));
  assert.equal(validSource(source('assets/plot.js')).length, 2);
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'vizualearner-path-'));
  try { await fs.mkdir(path.join(dir, 'source')); await fs.writeFile(path.join(dir, 'secret.txt'), 'secret'); await fs.symlink(path.join(dir, 'secret.txt'), path.join(dir, 'source/link.txt')); await assert.rejects(safeFile(path.join(dir, 'source'), 'link.txt')); }
  finally { await fs.rm(dir, { recursive: true, force: true }); }
});
